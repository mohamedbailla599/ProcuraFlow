CREATE SCHEMA IF NOT EXISTS schema_fournisseurs;
CREATE SCHEMA IF NOT EXISTS schema_commandes;
CREATE SCHEMA IF NOT EXISTS schema_receptions;
CREATE SCHEMA IF NOT EXISTS schema_factures;

-- Table Fournisseurs (Mohamed) — alignée avec le schéma Neon PostgreSQL 17 (procura_flow)
CREATE TABLE IF NOT EXISTS schema_fournisseurs.fournisseurs (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nom VARCHAR(150) NOT NULL CHECK (length(btrim(nom)) > 0),
    email VARCHAR(150) UNIQUE NOT NULL,
    telephone VARCHAR(30),
    adresse TEXT,
    actif BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

-- Table Commandes (Yassine)
CREATE TABLE IF NOT EXISTS schema_commandes.commandes (
    id SERIAL PRIMARY KEY,
    fournisseur_id INT NOT NULL,
    date_commande TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    statut VARCHAR(30) DEFAULT 'EN_ATTENTE',
    montant_total DECIMAL(10, 2) NOT NULL
);

CREATE TABLE IF NOT EXISTS schema_commandes.lignes_commande (
    id SERIAL PRIMARY KEY,
    commande_id INT REFERENCES schema_commandes.commandes(id) ON DELETE CASCADE,
    designation VARCHAR(150) NOT NULL,
    quantite INT NOT NULL,
    prix_unitaire DECIMAL(10, 2) NOT NULL
);

-- Table Factures (Hamza)
CREATE TABLE IF NOT EXISTS schema_factures.factures (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    numero_facture VARCHAR(50) UNIQUE,
    commande_id BIGINT NOT NULL,
    reception_id BIGINT NOT NULL,
    date_facture TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    montant_facture NUMERIC(12, 2) NOT NULL,
    statut_paiement VARCHAR(30) NOT NULL DEFAULT 'NON_PAYEE',
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);
