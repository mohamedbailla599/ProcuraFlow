CREATE TABLE IF NOT EXISTS schema_receptions.lignes_reception (
                                                                  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                                                                  reception_id BIGINT NOT NULL,
                                                                  ligne_commande_id BIGINT NOT NULL,
                                                                  quantite_recue INTEGER NOT NULL,
                                                                  remarques TEXT,

                                                                  CONSTRAINT lignes_reception_reception_id_fkey
                                                                  FOREIGN KEY (reception_id)
    REFERENCES schema_receptions.receptions(id)
    ON DELETE CASCADE,

    CONSTRAINT lignes_reception_quantite_check
    CHECK (quantite_recue > 0)
    );